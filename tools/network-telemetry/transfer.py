#!/usr/bin/env python3
"""Loopback transfers of generated payloads, for the network recorder's tests.

    transfer.py client PORT DOWN UP [--detach] [--heartbeat FILE] [--linger S] [--stubborn]
                                    [--echo] [--exit N]

The tests' server (`LoopbackServer` in support.py) listens on the host's
127.0.0.1; inside the measuring namespace pasta's gateway address stands for
it. A client downloads DOWN generated bytes (`GET n`) and then uploads UP
(`PUT n` and the bytes), each on its own connection, and writes one JSON line
to stderr saying what it moved.

`--detach` hands the transfers to a child in a new session whose parent has
already exited (a double fork), so only a measurement that follows the whole
process tree sees them. `--heartbeat FILE` makes that child append a line to
FILE every 0.1 s until it exits; `--linger S` keeps it alive S seconds after
its transfers; `--stubborn` makes it ignore SIGTERM, so only SIGKILL ends it.
`--echo` first copies stdin to stdout byte for byte, and `--exit N` is the
launch's own exit status. A DOWN and UP of 0 moves nothing.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import signal
import socket
import sys
import threading
import time
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Callable

CHUNK = 64 * 1024


def gateway() -> str:
    """The default route's gateway: inside pasta's namespace, the host's loopback."""
    for line in Path("/proc/net/route").read_text().splitlines()[1:]:
        fields = line.split()
        if fields[1] == "00000000":
            return socket.inet_ntoa(int(fields[2], 16).to_bytes(4, "little"))
    return "127.0.0.1"


def recv_upto(conn: socket.socket, n: int) -> int:
    """Read up to n bytes, stopping early at EOF; returns how many arrived, which
    the JSON line reports beside what was asked for."""
    got = 0
    while got < n:
        data = conn.recv(min(CHUNK, n - got))
        if not data:
            break
        got += len(data)
    return got


@dataclass(frozen=True)
class Moved:
    """What one client moved: the line it writes to stderr."""

    received: int
    sent: int
    reply: str = ""
    host: str = ""


# llmlint: ignore-block[async_typed_clients_at_boundaries] This is a test double moving opaque generated bytes to and from the tests' own loopback server so the recorder has traffic to count; there is no service API or response shape for a typed client to model, and a blocking socket is the simplest mover that cannot reorder or buffer what is counted.
def transfer(port: int, down: int, up: int) -> Moved:
    if not down and not up:
        return Moved(0, 0)
    host = gateway()
    got = 0
    if down:
        with socket.create_connection((host, port)) as conn:
            conn.sendall(f"GET {down}\n".encode())
            got = recv_upto(conn, down)
    reply = ""
    if up:
        with socket.create_connection((host, port)) as conn:
            conn.sendall(f"PUT {up}\n".encode() + os.urandom(up))
            reply = conn.recv(64).decode().strip()
    return Moved(got, up, reply, host)


# llmlint: ignore-end[async_typed_clients_at_boundaries]


def beat(path: str, stop: threading.Event) -> None:
    while not stop.is_set():
        with open(path, "a") as out:
            out.write(f"{os.getpid()} {time.time()}\n")
        stop.wait(0.1)


def child(args: argparse.Namespace) -> None:
    if args.stubborn:
        signal.signal(signal.SIGTERM, signal.SIG_IGN)
    stop = threading.Event()
    if args.heartbeat:
        threading.Thread(target=beat, args=(args.heartbeat, stop), daemon=True).start()
    if args.detach:
        time.sleep(0.3)  # the launch's own process has exited by now
    print(json.dumps(asdict(transfer(args.port, args.down, args.up))), file=sys.stderr, flush=True)
    time.sleep(args.linger)
    stop.set()


def whole(low: int, high: int) -> Callable[[str], int]:
    """An argparse type: an integer from `low` to `high`, else a usage error."""

    def parse(text: str) -> int:
        try:
            value = int(text)
        except ValueError:
            raise argparse.ArgumentTypeError(f"{text!r} is not an integer") from None
        if not low <= value <= high:
            raise argparse.ArgumentTypeError(f"{text!r} is outside {low}..{high}")
        return value

    return parse


def seconds(text: str) -> float:
    """An argparse type: a finite, non-negative number of seconds."""
    try:
        value = float(text)
    except ValueError:
        raise argparse.ArgumentTypeError(f"{text!r} is not a number of seconds") from None
    if not math.isfinite(value) or value < 0:
        raise argparse.ArgumentTypeError(
            f"{text!r} is not a finite, non-negative number of seconds"
        )
    return value


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", choices=["client"])
    parser.add_argument("port", type=whole(0, 65535), help="0 when nothing is moved")
    parser.add_argument("down", type=whole(0, 1 << 34))
    parser.add_argument("up", type=whole(0, 1 << 34))
    parser.add_argument("--detach", action="store_true")
    parser.add_argument("--heartbeat")
    parser.add_argument("--linger", type=seconds, default=0.0)
    parser.add_argument("--stubborn", action="store_true")
    parser.add_argument("--echo", action="store_true")
    parser.add_argument("--exit", type=whole(0, 255), default=0)
    # Anything after these is the harness argv the shim passed through, which
    # the double accepts and ignores, as a harness would act on it.
    args, _harness_argv = parser.parse_known_args()
    if args.echo:
        sys.stdout.buffer.write(sys.stdin.buffer.read())
        sys.stdout.buffer.flush()
    if not args.detach:
        child(args)
        return int(args.exit)
    if os.fork():
        return int(args.exit)
    os.setsid()
    if os.fork():
        os._exit(0)
    devnull = os.open(os.devnull, os.O_RDWR)
    for fd in (0, 1):
        os.dup2(devnull, fd)
    child(args)
    os._exit(0)


if __name__ == "__main__":
    sys.exit(main())
